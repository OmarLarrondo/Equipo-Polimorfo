package main.enums;

/**
 * Enumeración que representa los sabores de helado disponibles 
 * en la pizzería "El Pequeño Cesarín".
 * 
 * Según los requerimientos, existen exactamente 3 sabores de helado
 * que pueden ser servidos como base antes de agregar ingredientes extra.
 * 
 * @author Equipo-Polimorfo
 * @version 1.0
 */
public enum SaborHelado {
    
    /**
     * Sabor de helado de fresa
     */
    FRESA,
    
    /**
     * Sabor de helado de vainilla
     */
    VAINILLA,
    
    /**
     * Sabor de helado de chocolate
     */
    CHOCOLATE
    
}