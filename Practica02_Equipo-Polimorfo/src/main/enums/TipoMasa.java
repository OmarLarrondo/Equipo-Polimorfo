package enums;

/**
 * Enumeración que representa los tipos de masa disponibles para las pizzas
 * en la pizzería "El Pequeño Cesarín".
 * 
 * Según los requerimientos, antes de iniciar la preparación, el cliente
 * debe indicar el tipo de masa que quiere entre las opciones disponibles.
 * 
 * @author Equipo-Polimorfo
 * @version 1.0
 */
public enum TipoMasa {
    
    /**
     * Masa napolitana, caracterizada por ser más delgada y con bordes elevados
     */
    NAPOLITANA,
    
    /**
     * Masa romana, caracterizada por ser muy fina y crujiente
     */
    ROMANA,
    
    /**
     * Masa americana, caracterizada por ser más gruesa y esponjosa
     */
    AMERICANA
    
}