package main.MundoNinja;

/**
 * Enum que representa los Clanes de procedencia de un Aspirante o de un Voluntario.
 * 
 * FUCHIHA: Clan famoso por su poderoso Sharingan, una habilidad ocular que les otorga capacidades asombrosas para ver el chakra, copiar jutsus y lanzar genjutsus.
 * OSOMAKI: Clan conocido por su increíble fuerza vital,longevidad y gran habilidad en el Fūinjutsu (técnicas de sellado)
 * NACA: Clan especializado en el control de sombras y en la cría de ciervos, destacando por su inteligencia
 * MORTALIKA: Clan conocido por una habilidad sensorial llamada Habilidad Sísmica, que les permite detectar vibraciones en el suelo
 * AKIPICHI: Clan conocido por su habilidad única de convertir las calorías de su cuerpo en chakra.
 */

public enum ClanesDeProcedencia {
    FUCHIHA,
    OSOMAKI,
    NACA,
    MORTALIKA,
    AKIPICHI   
}

